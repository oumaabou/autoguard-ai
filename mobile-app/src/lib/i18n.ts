/** Simple `{name}` placeholder substitution - e.g.
 * t("diagnostic.analyzedAcrossSamples", { n: 4 }) -> "Analyzed across 4
 * acoustic samples from your recording." */
function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  let result = template;
  for (const [key, value] of Object.entries(vars)) {
    result = result.split(`{${key}}`).join(String(value));
  }
  return result;
}

export function useTranslation() {
  const { profile } = useProfile();
  const language = (profile?.language as LanguageCode) || DEFAULT_LANGUAGE;
  const dict = translations[language] ?? translations[DEFAULT_LANGUAGE];

  function t(key: TranslationKey, vars?: Record<string, string | number>): string {
    const template = dict[key] ?? translations[DEFAULT_LANGUAGE][key] ?? key;
    return interpolate(template, vars);
  }

  return { t, language };
}
