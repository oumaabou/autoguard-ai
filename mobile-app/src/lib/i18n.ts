/**
 * i18n.ts
 * =======
 * App-wide UI translations, driven by the persisted `language` profile
 * setting (see constants/language.ts, lib/profile.tsx). English is the
 * canonical key set - every other language must provide the same keys, and
 * a missing key at runtime falls back to English rather than crashing or
 * showing a raw key.
 *
 * Usage in a screen:
 *   import { useTranslation } from "../lib/i18n";
 *   const { t } = useTranslation();
 *   <Text>{t("dashboard.startListening")}</Text>
 *   <Text>{t("diagnostic.analyzedAcrossSamples", { n: windowsAnalyzed })}</Text>
 *
 * Scope: covers the main app screens (Dashboard, Evaluator, History,
 * Profile, Diagnostic's static chrome, Advocacy's static chrome, bottom
 * nav). Deliberately does NOT cover:
 *   - FAULT_INFO (constants/faults.ts) - the actual fault titles/summaries/
 *     causes shown on the Diagnostic screen. That's per-fault content tied
 *     to the ML output, not app chrome - a bigger, separate translation
 *     effort (6 faults x severity copy x every language).
 *   - The Welcome/Auth screens (index.tsx, auth.tsx) and the onboarding
 *     walkthrough - first-run-only, lower priority, not yet translated.
 *   - Dynamic content: the Advocacy chatbot's actual replies are already
 *     handled separately (see lib/api.ts's askQuestion -> backend
 *     rag_engine.py, which instructs Gemini/Groq to answer in this same
 *     language) - nothing to do here for that. Backend-sourced error
 *     messages (ApiError.message) also aren't covered - those come from
 *     the server, not this dictionary.
 */

